import type { Shoe, ShoePhoto, ShoeSize, ShoeView } from "@/components/shoe-wall";
import { avifFiles, photoEntries, photoFiles } from "./photos";

function photo(id: string, alt: string): ShoePhoto {
  const entry = photoEntries.find((p) => p.id === id);
  if (!entry) throw new Error(`no photo ${id}`);
  const widths = Object.keys(photoFiles[id]).map(Number);
  return {
    src: photoFiles[id][widths[widths.length - 1] >= 960 ? 960 : widths[0]],
    srcSet: widths.map((w) => `${photoFiles[id][w]} ${w}w`).join(", "),
    avifSrcSet: widths.map((w) => `${avifFiles[id][w]} ${w}w`).join(", "),
    width: entry.width,
    height: entry.height,
    baseline: entry.baseline,
    contact: entry.contact,
    lqip: entry.lqip,
    alt,
  };
}

const measure = (id: string) => {
  const entry = photoEntries.find((p) => p.id === id);
  return { hue: entry?.hue, lightness: entry?.lightness };
};

/** Stock per EU size, written out by hand so each shoe has its own gaps. */
function sizes(stock: Record<string, number>): ShoeSize[] {
  const chart: Record<string, [string, string]> = {
    "38": ["5.5", "5"],
    "39": ["6.5", "6"],
    "40": ["7", "6.5"],
    "41": ["8", "7"],
    "42": ["8.5", "8"],
    "43": ["9.5", "9"],
    "44": ["10", "9.5"],
    "45": ["11", "10.5"],
    "46": ["12", "11"],
  };
  return Object.entries(stock).map(([eu, count]) => ({
    eu,
    us: chart[eu][0],
    uk: chart[eu][1],
    stock: count,
    variantId: `v-${eu}`,
  }));
}

