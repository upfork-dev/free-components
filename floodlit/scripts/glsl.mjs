#!/usr/bin/env node
// Builds gl/*.glsl into src/components/floodlit/gl/shaders.ts: strips comments, inlines #include, keeps it small.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, "..", "gl");
const target = path.join(here, "..", "src", "components", "floodlit", "gl");

function read(name) {
  return fs.readFileSync(path.join(dir, name), "utf8").replace(/\r\n/g, "\n");
}

function expand(source) {
  return source.replace(/^#include "(.+)"$/gm, (_, file) => read(file));
}

function minify(source) {
  return source
    .replace(/\/\/.*$/gm, "")
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .join("\n");
}

const names = fs.readdirSync(dir).filter((f) => f.endsWith(".glsl") && f !== "common.glsl").sort();
let out = "// Generated by scripts/glsl.mjs from the .glsl files beside it. Do not edit by hand.\n";
for (const file of names) {
  const key = file.replace(/\.(vert|frag)\.glsl$/, (_, kind) => (kind === "vert" ? "Vert" : "Frag")).replace(/\.glsl$/, "");
  out += `export const ${key} = ${JSON.stringify(minify(expand(read(file))))};\n`;
}
fs.writeFileSync(path.join(target, "shaders.ts"), out);
console.log("shaders.ts", out.length, "chars,", names.length, "shaders");
